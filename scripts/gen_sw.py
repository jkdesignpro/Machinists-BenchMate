#!/usr/bin/env python3
"""Write app/sw.js, the service worker that lets the web version work offline.

It lists every file under app/ (except itself) to be stored on the first visit, and names
the store after a hash of all the files, so a new build replaces the old store. The desktop
app (Tauri) does not register it: its files are already on the machine.
Run by scripts/build-web.sh after everything else in app/ is built.
"""
import hashlib, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / "app"
files = sorted(p for p in APP.rglob("*") if p.is_file() and p.name not in ("sw.js",) and not p.name.startswith("."))
h = hashlib.sha256()
for p in files:
    h.update(str(p.relative_to(APP)).encode()); h.update(p.read_bytes())
version = h.hexdigest()[:12]
names = ["./"] + [p.relative_to(APP).as_posix() for p in files]

sw = """// Generated by scripts/gen_sw.py: do not edit by hand.
// Offline use of the web version: every file of the app is stored on the first visit; after that
// pages are served from the network when it answers and from the store when it does not.
'use strict';
const STORE = 'benchmate-%s';
const FILES = %s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(STORE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('benchmate-') && k !== STORE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== self.location.origin) return;
  e.respondWith(fetch(r).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(STORE).then(c => c.put(r, copy)); }
    return res;
  }).catch(() => caches.match(r, { ignoreSearch: true }).then(m => m || caches.match('./'))));
});
""" % (version, json.dumps(names, indent=0))
(APP / "sw.js").write_text(sw)
print(f"service worker: {len(names)} files, store benchmate-{version}")
