def merge(pair):
    a, b = pair; out = []
    for s in sorted(set(a) | set(b)):
        ws = sorted(set(a.get(s, [])) | set(b.get(s, [])))
        out.append([s, [[w, (1 if w in a.get(s, []) else 0) | (2 if w in b.get(s, []) else 0)] for w in ws]])
    return out

