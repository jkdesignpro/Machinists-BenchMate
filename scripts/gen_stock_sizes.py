def lab(v, inch):
    if not inch: return ('%g' % v)
    w = int(v + 1e-9); r = round((v - w) * 16)
    if abs(v - w - r / 16) > 1e-6: return ('%.3f' % v).lstrip('0')
    if r == 0: return str(w)
    n, d = r, 16
    while n % 2 == 0: n //= 2; d //= 2
    return (str(w) + '-' if w else '') + '%d/%d' % (n, d)

def merge(pair, inch=False):
    a, b = pair; out = []
    for k in sorted(set(a) | set(b), key=lambda k: (k[0], k[1] if len(k) > 1 else 0)):
        ws = sorted(set(a.get(k, [])) | set(b.get(k, [])))
        name = ('Ø ' + lab(k[0], inch)) if len(k) == 1 else ' x '.join(lab(x, inch) for x in k)
        out.append([name, list(k), [[w, (1 if w in a.get(k, []) else 0) | (2 if w in b.get(k, []) else 0)] for w in ws]])
    return out

