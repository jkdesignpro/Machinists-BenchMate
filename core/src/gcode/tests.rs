//! Golden-output tests: each case generates a program and compares the text
//! with `golden/<name>.nc`. Run with BLESS=1 to rewrite the files after a
//! deliberate change, then review the diff by hand.
use super::*;

fn golden(name: &str, p: &Program) {
    assert!(p.error.is_none(), "{name}: {:?}", p.error);
    let path = format!("{}/src/gcode/golden/{}.nc", env!("CARGO_MANIFEST_DIR"), name);
    if std::env::var("BLESS").is_ok() { std::fs::write(&path, &p.text).unwrap(); return; }
    let want = std::fs::read_to_string(&path).unwrap_or_else(|_| panic!("missing golden file {path}; run with BLESS=1"));
    assert_eq!(p.text, want, "{name} differs from its golden file");
    check_words(name, &p.text);
}

/// Structural checks every program must pass: warning header, units, and a
/// decimal point in every coordinate and feed word.
fn check_words(name: &str, t: &str) {
    assert!(t.contains("(GENERATED BY MACHINISTS BENCHMATE)"), "{name}: header");
    assert!(t.contains("(CHECK EVERY LINE AGAINST YOUR CONTROL MANUAL)"), "{name}: header");
    assert!(t.contains("(PROVE OUT IN SINGLE BLOCK"), "{name}: header");
    assert!(t.contains("G21") || t.contains("G20"), "{name}: units");
    assert!(t.trim_end().ends_with('%'));
    for line in t.lines() {
        if line.starts_with('(') || line == "%" { continue; }
        let code = line.split('(').next().unwrap();
        for w in code.split_whitespace() {
            let c = w.chars().next().unwrap();
            if "XYZIJKRUWF".contains(c) { assert!(w.contains('.'), "{name}: word {w} in '{line}' has no decimal point"); }
        }
    }
}

