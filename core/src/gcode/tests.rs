/// Arcs are consistent (start and end at the same distance from the centre)
/// and the lead-in ends tangent to the thread circle.
#[test] fn threadmill_geometry() {
    for internal in [true, false] { for climb in [true, false] { for lh in [false, true] {
        let mut j = tmill(internal, Ctrl::Generic, false); j.climb = climb; j.left_hand = lh;
        let p = gen_thread_mill(&j);
        assert!(p.error.is_none());
        let mut prev = p.start;
        let mut arcs = 0;
        for m in &p.moves {
            if m.kind == 2 || m.kind == 3 {
                let r0 = ((prev[0] - m.cx).powi(2) + (prev[1] - m.cy).powi(2)).sqrt();
                let r1 = ((m.x - m.cx).powi(2) + (m.y - m.cy).powi(2)).sqrt();
                assert!((r0 - r1).abs() < 1e-9, "arc radius mismatch {r0} {r1}");
                arcs += 1;
            }
            if m.kind != 4 { prev = [m.x, m.y, m.z]; }
        }
        assert!(arcs >= 3);
        // Helix direction: internal climb = CCW (G03); right hand rises when CCW.
        let helix = p.moves.iter().find(|m| (m.kind == 2 || m.kind == 3) && m.cx == 0.0 && m.cy == 0.0).unwrap();
        assert_eq!(helix.kind == 3, internal == climb);
        let first_z = p.moves.iter().filter(|m| m.kind == 3 || m.kind == 2).map(|m| m.z).collect::<Vec<_>>();
        let rising = first_z[1] > first_z[0];
        assert_eq!(rising, (internal == climb) != lh);
        // Tangency: at the lead-in end point, the lead arc radius vector and the thread radius vector are parallel.
        let lead = p.moves.iter().find(|m| m.kind == 2 || m.kind == 3).unwrap();
        let v1 = (lead.x - lead.cx, lead.y - lead.cy); let v2 = (lead.x, lead.y);
        assert!((v1.0 * v2.1 - v1.1 * v2.0).abs() < 1e-9);
    }}}
}

