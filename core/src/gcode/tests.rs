#[test] fn deterministic_and_flat_parse() {
    // The flat interface used by the app gives the same program as the struct.
    let v = [1.0, 0.0, 1001.0, 3.0, 83.0, 1.0, 1.0, 54.0, 1200.0, 150.0, 1.5, 25.0, 2.0, -20.0, 4.0, 0.5, 1.0, 4.0,
        50.0, 0.0, 0.0, 50.0, -50.0, 0.0, 0.0, -50.0];
    let a = run_flat(cyc::DRILL, &v);
    let b = run_flat(cyc::DRILL, &v);
    assert_eq!(a.text, b.text);
    let mut j = drill(true, Ctrl::Generic, 83);
    j.holes = vec![(50.0, 0.0), (0.0, 50.0), (-50.0, 0.0), (0.0, -50.0)];
    assert_eq!(a.text, gen_drill(&j).text);
}
