#[test] fn drill_time_single_hole() {
    // One hole, G81, G98: rapid Z25 -> R2 (23), feed 22 at 150 mm/min, rapid Z-20 -> Z25 (45).
    let mut j = drill(true, Ctrl::Generic, 81);
    j.holes = vec![(0.0, 0.0)]; j.ret_r = false;
    let p = gen_drill(&j);
    let (tf, tr, td) = p.time(5000.0);
    assert!((tf - 22.0 / 150.0 * 60.0).abs() < 1e-9);
    assert!((tr - 68.0 / 5000.0 * 60.0).abs() < 1e-9);
    assert_eq!(td, 0.0);
}

