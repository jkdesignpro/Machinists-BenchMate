fn mean(k: usize) -> f64 { iso286_step_mean(STEPS[k].0, STEPS[k].1) }

#[test] fn tolerance_factor() {
    // 18-30 mm: D = sqrt(540) = 23.238, i = 1.3073 um
    assert!((iso286_tolerance_factor(mean(4)) - 1.3073).abs() < 1e-4);
    assert_eq!(iso286_it_multiplier(7), 16.0);
    assert_eq!(iso286_it_multiplier(18), 2500.0);
}

/// IT5..IT10 above 3 mm: the formula with BenchMate's reconstructed rounding
/// reproduces the published table except in exactly these 10 cells. ISO/R
/// 286:1962 itself notes one of them (IT6, 3 to 6 mm: 7.5 rounded to 8).
#[test] fn it_formula_vs_table() {
    let exceptions = [(1, 6), (1, 9), (1, 10), (2, 7), (2, 10), (3, 7), (3, 10), (11, 6), (12, 6), (12, 7)];
    let mut bad = Vec::new();
    for k in 1..13 {
        for g in 5..=10 {
            let r = iso286_it_rounded(mean(k), g as u32);
            let off = (r - it(k, g)).abs() > 1e-9;
            if off != exceptions.contains(&(k, g)) { bad.push((STEPS[k], g, r, it(k, g))); }
            if off { assert!((r - it(k, g)).abs() <= 1.0 + 1e-9, "{:?} IT{g}: {r} vs {}", STEPS[k], it(k, g)); }
        }
    }
    assert!(bad.is_empty(), "{bad:?}");
}

/// The published table follows IT(n+5) = 10 x IT(n) exactly from IT7 up,
/// and from IT6 except over 3 to 6 mm (IT6 = 8 but IT11 = 75, from the
/// unrounded 7.5).
#[test] fn it_times_ten_rule() {
    for k in 0..13 {
        for n in 6..=13 {
            let ok = (it(k, n + 5) - 10.0 * it(k, n)).abs() < 1e-9;
            assert_eq!(ok, !(n == 6 && k == 1), "{:?} IT{n}", STEPS[k]);
        }
    }
}

/// Up to 3 mm the published IT values are not the formula values (the
/// formula gives 5.4 um for IT6, the table 6); documented, not used.
#[test] fn it_first_step_is_not_formula() {
    assert!((iso286_it_formula(mean(0), 6) - 5.42).abs() < 0.01);
    assert_eq!(it(0, 6), 6.0);
}

/// Shaft deviations d, e, f, g, k, n above 3 mm agree with the annex
/// formulas to within the rounding of the tables (the larger of 1 um and
/// 2.5 %); m equals IT7 - IT6 exactly; p lies in IT7 + 0..5 and s (to 50
/// mm) in IT8 + 1..4, as the formulas state.
#[test] fn shaft_deviations_vs_formula() {
    for k in 1..13 {
        let d = mean(k);
        let f = |l: u32| iso286_shaft_fd_formula(l, d, it(k, 6), it(k, 7), it(k, 8), it(k, 9), it(k, 10));
        for (l, tab) in [(5u32, D_[k]), (6, E_[k]), (8, F_[k]), (10, G_[k]), (13, K_[k]), (15, N_[k])] {
            let c = f(l);
            assert!((c - tab).abs() <= (0.025 * c.abs()).max(1.0), "{} {:?}: formula {c:.2} table {tab}", LETTERS[l as usize], STEPS[k]);
        }
        assert_eq!(f(14), M_[k]);
        assert!(P_[k] >= it(k, 7) && P_[k] <= it(k, 7) + 5.0, "p {:?}", STEPS[k]);
        if k <= 5 { assert!(S_TO_50[k] >= it(k, 8) + 1.0 && S_TO_50[k] <= it(k, 8) + 4.0, "s {:?}", STEPS[k]); }
    }
    // up to 3 mm the tables were set from experience: m = 2 (IT7 - IT6 = 4), n = 4 (formula 6.0)
    assert_eq!(M_[0], 2.0);
    assert!((iso286_shaft_fd_formula(15, mean(0), 6.0, 10.0, 14.0, 25.0, 40.0) - 6.0).abs() < 0.05);
}

