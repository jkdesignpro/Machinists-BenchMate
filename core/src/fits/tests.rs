/// Worked examples printed by RoyMech ("How to use ISO tolerances"):
/// 40 H7 +25/0 with g6 -9/-25; 110 H11 +220/0, e9 -72/-159; 300 K7 +16/-36.
#[test] fn roymech_examples() {
    let h7 = iso286_hole_limits(11, 7, 0.0, 0.0, 25.0, 30.0, 50.0);
    assert_eq!(h7, (25.0, 0.0));
    assert_eq!(iso286_shaft_limits(10, 6, -9.0, 16.0), (-9.0, -25.0));
    assert_eq!(iso286_shaft_limits(6, 9, -72.0, 87.0), (-72.0, -159.0));
    assert_eq!(iso286_hole_limits(11, 11, 0.0, 0.0, 220.0, 80.0, 120.0), (220.0, 0.0));
    let d = iso286_delta(52.0, 32.0, 315.0);
    assert_eq!(iso286_hole_limits(13, 7, 4.0, d, 52.0, 250.0, 315.0), (16.0, -36.0));
    // fit H7/g6 at 40 mm: clearance 9 to 50 um
    let (mx, mn) = iso286_fit(25.0, 0.0, -9.0, -25.0);
    assert_eq!((mx, mn), (50.0, 9.0));
    assert_eq!(iso286_fit_type(mx, mn), 1.0);
    // H7/p6 at 40 mm: p6 +42/+26 -> -42 to -1 (interference)
    let p6 = iso286_shaft_limits(16, 6, 26.0, 16.0);
    let (mx, mn) = iso286_fit(25.0, 0.0, p6.0, p6.1);
    assert_eq!((mx, mn), (-1.0, -42.0));
    assert_eq!(iso286_fit_type(mx, mn), 3.0);
    // H7/k6 at 40 mm: k6 +18/+2 -> +23 to -18 (transition)
    let k6 = iso286_shaft_limits(13, 6, 2.0, 16.0);
    assert_eq!(k6, (18.0, 2.0));
    assert_eq!(iso286_fit_type(25.0 - 2.0, 0.0 - 18.0), 2.0);
}

